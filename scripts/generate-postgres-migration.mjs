import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const sourceDirectory = new URL("../drizzle/", import.meta.url);
const target = new URL("../supabase/postgres/0001_nic_app.sql", import.meta.url);

const files = (await readdir(sourceDirectory))
  .filter((name) => /^\d{4}.*\.sql$/.test(name))
  .sort();

const statements = [];
for (const file of files) {
  const sql = await readFile(join(fileURLToPath(sourceDirectory), file), "utf8");
  for (const raw of sql.split("--> statement-breakpoint")) {
    const statement = raw.trim();
    if (!statement || /^CREATE\s+TRIGGER\b/i.test(statement)) continue;
    statements.push(
      statement
        .replaceAll("`", '"')
        .replace(/\bINSERT\s+OR\s+IGNORE\s+INTO\b/gi, "INSERT INTO")
        .replace(/;\s*$/, ""),
    );
  }
}

// SQLite permits a foreign key to reference a table declared later. PostgreSQL
// resolves the referenced relation at DDL time, so bootstrap users first.
statements.sort((left, right) => {
  const priority = (statement) =>
    /^CREATE TABLE "users"/i.test(statement) ? 0
      : /^CREATE UNIQUE INDEX "users_email_unique"/i.test(statement) ? 1
        : 2;
  return priority(left) - priority(right);
});

const invariantTriggers = String.raw`
CREATE OR REPLACE FUNCTION nic_app.reject_resource_booking_overlap()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'confirmed' AND EXISTS (
    SELECT 1 FROM nic_app.resource_bookings booking
    WHERE booking.resource_id = NEW.resource_id
      AND booking.status = 'confirmed'
      AND booking.starts_at < NEW.ends_at
      AND booking.ends_at > NEW.starts_at
  ) THEN
    RAISE EXCEPTION 'RESOURCE_BOOKING_OVERLAP' USING ERRCODE = '23P01';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER resource_booking_no_overlap_insert
BEFORE INSERT OR UPDATE OF resource_id, starts_at, ends_at, status
ON nic_app.resource_bookings FOR EACH ROW EXECUTE FUNCTION nic_app.reject_resource_booking_overlap();

CREATE OR REPLACE FUNCTION nic_app.reject_cost_snapshot_update()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'COST_SNAPSHOT_IMMUTABLE' USING ERRCODE = '23000';
END;
$$;
CREATE TRIGGER work_order_cost_snapshot_immutable
BEFORE UPDATE OF quantity_milli, unit_price_minor, tax_bps, discount_bps,
  subtotal_minor, discount_minor, tax_minor, line_total_minor, currency, catalog_record_id
ON nic_app.work_order_cost_lines FOR EACH ROW EXECUTE FUNCTION nic_app.reject_cost_snapshot_update();

CREATE OR REPLACE FUNCTION nic_app.reject_qr_replay()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.redeemed_at IS NOT NULL THEN
    RAISE EXCEPTION 'QR_ALREADY_REDEEMED' USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER visitor_qr_no_replay
BEFORE UPDATE OF redeemed_at ON nic_app.visitor_qr_tokens
FOR EACH ROW EXECUTE FUNCTION nic_app.reject_qr_replay();

CREATE OR REPLACE FUNCTION nic_app.reject_master_data_hard_delete()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'draft' THEN
    RAISE EXCEPTION 'MASTER_DATA_HARD_DELETE_FORBIDDEN' USING ERRCODE = '23000';
  END IF;
  RETURN OLD;
END;
$$;
CREATE TRIGGER master_data_no_hard_delete
BEFORE DELETE ON nic_app.master_data_records
FOR EACH ROW EXECUTE FUNCTION nic_app.reject_master_data_hard_delete();

CREATE OR REPLACE FUNCTION nic_app.guard_purchase_order_issue()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'issued' AND (OLD.status <> 'approved' OR NEW.approved_by IS NULL) THEN
    RAISE EXCEPTION 'PO_APPROVAL_REQUIRED' USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER purchase_order_issue_guard
BEFORE UPDATE OF status ON nic_app.purchase_orders
FOR EACH ROW EXECUTE FUNCTION nic_app.guard_purchase_order_issue();

CREATE OR REPLACE FUNCTION nic_app.guard_goods_receipt_quantity()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  ordered bigint;
  received bigint;
BEGIN
  SELECT quantity_milli INTO ordered
  FROM nic_app.purchase_order_lines WHERE id = NEW.purchase_order_line_id;
  SELECT COALESCE(sum(line.quantity_received_milli), 0) INTO received
  FROM nic_app.goods_receipt_lines line
  JOIN nic_app.goods_receipts receipt ON receipt.id = line.receipt_id
  WHERE line.purchase_order_line_id = NEW.purchase_order_line_id
    AND receipt.status = 'posted';
  IF received + NEW.quantity_received_milli > ordered THEN
    RAISE EXCEPTION 'RECEIPT_EXCEEDS_PO' USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER goods_receipt_quantity_guard
BEFORE INSERT OR UPDATE OF quantity_received_milli ON nic_app.goods_receipt_lines
FOR EACH ROW EXECUTE FUNCTION nic_app.guard_goods_receipt_quantity();
`;

const output = `-- Generated by scripts/generate-postgres-migration.mjs.
-- The application owns an isolated schema so it cannot collide with the legacy
-- public Supabase/RLS prototype.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS nic_app;
REVOKE ALL ON SCHEMA nic_app FROM PUBLIC, anon, authenticated;
SET LOCAL search_path = nic_app, public;

${statements.map((statement) => `${statement};`).join("\n\n")}

${invariantTriggers}

CREATE TABLE IF NOT EXISTS nic_app.schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO nic_app.schema_migrations(version) VALUES ('0001_nic_app')
ON CONFLICT (version) DO NOTHING;
COMMIT;
`;

await writeFile(target, output, "utf8");
console.log(`Generated ${fileURLToPath(target).replace(fileURLToPath(root), "")} from ${files.length} D1 migrations.`);
